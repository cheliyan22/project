"""Capture the registered shared Chromium, never launch another browser.
Generated by CodeRabbit for this experimental task. Requires coderabbit-agent-browser.
"""
import json,subprocess,pathlib,time,os
out=pathlib.Path(os.environ['WORKSPACE_ROOT'])/'output'/os.environ.get('REBOOT_CAPTURE_DIR','babylon-cities');out.mkdir(parents=True,exist_ok=True)
ids=['ai','gaming','education','health','creative','revival','graveyard','success','space','robotics','community']
def browser(*args):
 r=subprocess.run(['coderabbit-agent-browser',*args],capture_output=True,text=True,timeout=90)
 if r.returncode:raise RuntimeError(r.stderr+r.stdout)
 return r.stdout.strip()
browser('set','viewport','1440','1000')
browser('set','media','reduced-motion')
results=[]
for city in ids:
 browser('open',f'http://localhost:5173/?city={city}&capture=1&quality=high')
 browser('wait','--fn',f'window.__rebootBabylon?.city === "{city}" && window.__rebootBabylon?.ready === true')
 browser('eval','window.__rebootCapture?.()')
 browser('eval','document.querySelector(".bw-overlay").style.visibility="hidden"')
 browser('screenshot',str(out/(city+'.png')))
 raw=browser('eval','JSON.stringify(window.__rebootBabylon)')
 try:
  metrics=json.loads(raw)
  if isinstance(metrics,str):metrics=json.loads(metrics)
 except json.JSONDecodeError:metrics={'raw':raw}
 if not isinstance(metrics,dict) or metrics.get('city')!=city or metrics.get('quality')!='high':raise RuntimeError('Scene changed during capture; retry '+city)
 results.append(metrics)
 (out/'metrics.json').write_text(json.dumps({'generatedBy':'CodeRabbit','renderer':'shared Chromium software WebGL','camera':{'alpha':.3*3.141592653589793,'beta':1.30,'radius':285,'target':[0,30,0]},'results':results},indent=2))
 print(city,metrics,flush=True)
browser('open','http://localhost:5173/?city=health')
